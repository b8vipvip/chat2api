_TOPICS = {"A": A_TOPICS, "B": B_TOPICS, "C": C_TOPICS, "D": D_TOPICS}
_KIND = {"A": "rich_text", "B": "three_images", "C": "four_files", "D": "web_app"}


def build_v5_case(scene: str, ordinal: int) -> dict:
    if scene not in _TOPICS or not isinstance(ordinal, int) or ordinal < 0:
        raise ValueError("Invalid V5 scene ordinal")
    topics = _TOPICS[scene]
    epoch, index = divmod(ordinal, len(topics))
    topic = topics[index]
    edition = epoch + 1
    if scene == "A":
        title, context, focus = topic
        budget = 36 + (index % 5) * 13 + epoch * 7
        months = (9, 12, 18, 24)[index % 4] + epoch * 3
        prompts = [(
            f"我计划{context}，项目暂定《{title}》，这是第{edition}次独立运营方案评估。"
            f"请提供完整的{months}个月商业经营报告，最高启动投入{budget}万元；"
            "涵盖市场假设与竞争、客户画像、设施、人力、成本定价、采购与风险、现金流和实施里程碑。"
            f"请重点建立{focus}的量化模型，并将事实与估计区分。"
            "至少写三张内容不同且可直接渲染的Markdown表格、一个可独立运行且包含输入校验的Python示例、"
            "至少两个LaTeX公式、一份Mermaid决策流程图，以及至少12项带负责人、期限和验收标准的行动。"
            "正文必须完整，最后以《最终建议》为标题总结优先级和风险。"
        )]
        end_anchor = "最终建议"
    elif scene == "B":
        title, hero, opening, conflict, finale = topic
        ratio = ("3:4", "4:5", "2:3")[index % 3]
        prompts = [(
            f"为第{edition}辑原创绘本《{title}》编写三幕连续故事，主角是{hero}，"
            "严格保持外观、服装和随身物品一致。"
            f"请分别实际生成三张可下载的独立高清竖版{ratio}插画："
            f"第一幕《{opening}》、第二幕《{conflict}》、第三幕《{finale}》。"
            "三张必须分别生成，不得用一张拼图、网络图片、绘图提示词或代码冒充。"
            "结合每张作品解释画面构图和三幕因果关系，附上独立图片链接和对应说明。"
        )]
        end_anchor = ""
    elif scene == "C":
        title, objective, data_fields = topic
        visitors = 140 + (index % 6) * 55 + epoch * 30
        prompts = [(
            f"筹办第{edition}届《{title}》，目标是{objective}，预计参与{visitors}人。"
            "请制定完整活动执行方案并交付四份互相对应的、可实际下载打开编辑的文件："
            "(1) event_budget_and_schedule.xlsx：含分表预算、公式、排期、人员排班、库存与至少一张图表；"
            "(2) event_pitch_deck.pptx：不少于10页，含招商与风险评估、时间线和数据图表；"
            f"(3) event_structured_data.json：合法JSON，包含{data_fields}、活动预算、风险及负责人数据；"
            "(4) event_delivery_bundle.zip：打包前三个真实文件并含README说明数据字段和使用方法。"
            "四份文件的数字与身份必须一致，估算须标明，不得返回代码块、假链接或路径来冒充文件。"
            "正文还需说明关键岗位、应急预案、验收方法，并逐个给出可用的下载链接。"
        )]
        end_anchor = ""
    else:
        title, setting, mechanics, edges = topic
        prompts = [(
            f"为{setting}开发第{edition}个原创离线单页HTML演示应用《{title}》。"
            "请实际生成并交付一个可以直接下载的 app_demo.html；"
            "双击本地HTML就能运行，不能依赖CDN、服务器、外部图像、字体或任何第三方包。"
            f"页面必须实现：{mechanics}；并严谨处理{edges}。"
            "至少含20条不涉及真实个人信息的示例数据，提供搜索、筛选、排序、添加修改删除、"
            "持久化localStorage、完整导入导出JSON、错误回滚、键盘可访问性、移动端响应式布局与清晰提示。"
            "每个按钮和表单必须有实际行为；先给可下载的真实HTML，再给主要数据模型、Mermaid流程图、"
            "不少于15项覆盖边界情况的验收步骤和后续接入数据库建议。"
        )]
        end_anchor = ""
    return {
        "scene": scene, "serial": ordinal, "title": topic[0],
        "prompts": prompts, "end_anchor": end_anchor,
        "keywords": [topic[0]], "kind": _KIND[scene],
        "case_version": "v5", "pool_version": V5_VERSION,
    }
